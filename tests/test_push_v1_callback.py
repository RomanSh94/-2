def _make_callback_update(data, message_id, chat_id=USER_ID, uid=USER_ID):
    return Update.model_validate({
        "update_id": next(_id_counter),
        "callback_query": {
            "id": str(next(_id_counter)),
            "from": {"id": uid, "is_bot": False, "first_name": "T"},
            "message": {
                "message_id": message_id,
                "date": int(time.time()),
                "chat": {"id": chat_id, "type": "private"},
                "text": "placeholder",
            },
            "chat_instance": "1",
            "data": data,
        },
    }, context={"bot": bot.bot})


async def _seed_inactive_user(uid=USER_ID, days_inactive=2):
    await database.upsert_user(uid, "u", "U", "ru")
    async with database.aiosqlite.connect(database.DB) as db:
        await db.execute(
            "UPDATE users SET last_seen=datetime('now', ?) WHERE id=?",
            (f"-{days_inactive} days", uid))
        await db.commit()


async def _seed_conversation_anchor(uid=USER_ID):
    """A genuine prior conversational assistant turn -- required for the
    scheduler to send the Push V1 card at all (Correction #1, Blocker 5).
    Returns the new messages row id."""
    return await database.save_message(
        uid, "assistant", "prior reply", "open_chat", "ru",
        source=database.MessageSource.ASSISTANT_DELIVERED)


async def _deliver_real_push(stub, uid=USER_ID, with_anchor=True):
    """Drives the REAL send path (scheduler._send_silence_pushes) through
    the SAME stub session bot.py's dispatcher uses, so the resulting
    chat_id/message_id/tokens are exactly what production would hand back
    to Telegram -- never hand-constructed. Seeds a real conversation anchor
    by default (with_anchor=True) since the scheduler now refuses to send
    at all without one (Correction #1, Blocker 5) -- callers testing
    anchor semantics themselves pass with_anchor=False or manage the
    anchor row directly. Returns
    (chat_id, message_id, continue_token, new_topic_token)."""
    await _seed_inactive_user(uid)
    if with_anchor:
        await _seed_conversation_anchor(uid)
    await scheduler._send_silence_pushes(bot.bot)
    async with database.aiosqlite.connect(database.DB) as db:
        cur = await db.execute(
            "SELECT token, action, chat_id, source_message_id FROM push_action_bindings "
            "WHERE user_id=? AND consumed_at IS NULL AND superseded_at IS NULL", (uid,))
        rows = await cur.fetchall()
    by_action = {r[1]: r for r in rows}
    assert set(by_action) == {"push_continue", "push_new_topic"}, \
        "push delivery did not produce the expected 2 open bindings"
    chat_id = by_action["push_continue"][2]
    message_id = by_action["push_continue"][3]
    return chat_id, message_id, by_action["push_continue"][0], by_action["push_new_topic"][0]


