# ── active journal FSM is abandoned (not contaminated) on a valid tap ──────
def test_continue_tap_clears_a_stale_active_journal_fsm(_common):
    async def run():
        chat_id, message_id, continue_token, _ = await _deliver_real_push(_common)
        # Seed a real, active EmotionJournal FSM via the SAME MemoryStorage
        # the real dispatcher resolves for this (bot, chat, user) -- mirrors
        # tests/test_journal_navigation_dispatch.py's technique.
        ctx = bot.dp.fsm.get_context(bot.bot, chat_id=USER_ID, user_id=USER_ID)
        await ctx.set_state(bot.EmotionJournal.active)
        await ctx.set_data({"jstep": 1, "jdata": {"event": "x"}, "orange": False, "nudged": False})

        await bot.dp.feed_update(
            bot.bot, _make_callback_update(f"pushbtn:{continue_token}", message_id, chat_id))
        return ctx
    ctx = asyncio.run(run())
    assert asyncio.run(ctx.get_state()) is None
    assert asyncio.run(ctx.get_data()) == {}
    # _deliver_real_push seeds a real anchor by default, so the resume
    # opener is expected here -- this test's own concern is the journal
    # FSM clear above, not anchor semantics (covered separately).
    assert prompts.PUSH_V1_CONTINUE_REPLY_RU in _common.texts()
